"""(cursedsound) cursed-os's face: Press Start 2P (SIL OFL 1.1, The Press Start 2P Project Authors) on its own 8 x 8 grid,
1 bit a pixel, printable ASCII 32..95 (the UI folds to capitals). cos.c draws it 1:1 for labels and twice as tall for
values. 512 bytes, where two antialiased faces took 4.7 KB of the flash.

  gen_cos_font.py OUT.h
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT = Path(__file__).resolve().parents[1] / "assets" / "fonts" / "PressStart2P-Regular.ttf"


def main():
    out = Path(sys.argv[1])
    f = ImageFont.truetype(str(FONT), 8)
    rows = []
    for c in range(32, 96):
        im = Image.new("1", (8, 8), 0)
        ImageDraw.Draw(im).text((0, 0), chr(c), font=f, fill=1)
        rows.append([sum(im.getpixel((x, y)) << (7 - x) for x in range(8)) for y in range(8)])
    lines = ["/* generated by tools/gen_cos_font.py: Press Start 2P (SIL OFL 1.1, The Press Start 2P Project Authors), 8 x 8,",
             " * 1 bit a pixel (bit 7 the left), ASCII 32 .. 95 */", "#pragma once", "#include <stdint.h>",
             "static const uint8_t COS_FONT[64][8] = {"]
    lines += ["    {" + ", ".join(f"0x{b:02x}" for b in r) + f"}},   /* {chr(32 + i)!r} */" for i, r in enumerate(rows)]
    lines += ["};", ""]
    out.write_text("\n".join(lines))
    print(f"cos font: 64 glyphs, 512 B -> {out}")


if __name__ == "__main__":
    main()
