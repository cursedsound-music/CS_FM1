"""firmware/src/xr_tables.h: tables for cursed-os 0.11's FMDRUM engine, TRANSIENT layer and DIST TUBE / RAT.

The TUBE (ECC83 triode) and RAT (1N914 diode) transfer curves and the twelve transient samples are taken from the LXR
drum machine's firmware (Copyright (C) 2012-2026 Erica Synths, GPL-3.0-only; Core/Src/Soundengine/DSPAudio/FX/
Distortion.c and transientTables.c): the curves turned from floating point into Q15 for the FM-1 (no FPU), the samples
(signed 8 bits, 44.1 kHz, 2205 each, ~50 ms) as they are.

    python3 tools/gen_xr_tables.py <LXR Distortion.c> <LXR transientTables.c> > firmware/src/xr_tables.h"""
import math, random, re, sys

src = open(sys.argv[1]).read()
def table(name):
    m = re.search(name + r"\[(\d+)\]\s*=\s*\{(.*?)\}", src, re.S)
    vals = [float(x) for x in re.findall(r"-?\d+\.?\d*(?:[eE]-?\d+)?", m.group(2))]
    assert len(vals) == int(m.group(1)), (name, len(vals))
    return vals
ecc = table("ecc83Table")
dio = table("table_1n914")
q15 = lambda v: max(-32767, min(32767, int(round(v * 32767))))

# the transients: transientData[12][2205], each block after its "//name" comment
tsrc = open(sys.argv[2]).read()
body = tsrc[tsrc.index("transientData"):]
body = body[body.index("{") + 1:]
SAMPLES = []
i = 0
while True:
    a = body.find("{", i)
    if a < 0:
        break
    b = body.index("}", a)
    name = re.findall(r"//\s*(.+)", body[i:a])
    vals = [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|-?\d+", body[a + 1:b])]
    vals = [v - 256 if v > 127 else v for v in vals]
    assert 0 < len(vals) <= 2205, (name, len(vals))
    vals += [0] * (2205 - len(vals))                     # (C fills a short one with 0, as transientTables.c's last)
    SAMPLES.append((name[-1].strip() if name else "?", vals))
    i = b + 1
assert len(SAMPLES) == 12, len(SAMPLES)

print("/* SPDX-License-Identifier: GPL-3.0-only")
print(" * generated by tools/gen_xr_tables.py: do not edit */")
print("/* the TUBE (ECC83) and RAT (1N914) curves: from the LXR firmware (Copyright (C) 2012-2026 Erica Synths, GPL-3.0-only,")
print(" * Distortion.c), in Q15; index (x + 1) * 64 (TUBE, 129 points), (x + 1) * 128 (RAT, 257 points) */")
print("static const int16_t XR_TUBE[129] = {" + ", ".join(str(q15(v)) for v in ecc) + "};")
print("static const int16_t XR_DIODE[257] = {" + ", ".join(str(q15(v)) for v in dio) + "};")
print("/* the transients: the LXR firmware's (transientTables.c, Copyright (C) 2012-2026 Erica Synths, GPL-3.0-only), signed")
print(" * 8 bits, 44.1 kHz, 2205 samples (~50 ms) each; its sources' names as it gives them */")
print("#define XR_TRN_N %d" % len(SAMPLES))
print("#define XR_TRN_LEN 2205u")
print("static const int8_t XR_TRN[XR_TRN_N][XR_TRN_LEN] = {")
for name, v in SAMPLES:
    print("    {" + ", ".join(str(x) for x in v) + "},   /* %s */" % name.replace("*/", ""))
print("};")
