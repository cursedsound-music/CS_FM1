"""firmware/src/xr_tables.h: tables for cursed-os 0.11's FMDRUM engine, TRANSIENT layer and DIST TUBE / RAT.

The TUBE (ECC83 triode) and RAT (1N914 diode) transfer curves are taken from the LXR drum machine's firmware
(Copyright (C) 2012-2026 Erica Synths, GPL-3.0-only; Core/Src/Soundengine/DSPAudio/FX/Distortion.c), turned from
floating point into Q15 for the FM-1 (no FPU). The transients are cursed-os's own, synthesised here (the LXR's are
samples of recordings; these are not those): 1024 samples of 8 bits at 44.1 kHz each.

    python3 tools/gen_xr_tables.py <LXR Distortion.c> > firmware/src/xr_tables.h"""
import math, random, re, sys

src = open(sys.argv[1]).read()
def table(name):
    m = re.search(name + r"\[(\d+)\]\s*=\s*\{(.*?)\}", src, re.S)
    vals = [float(x) for x in re.findall(r"-?\d+\.?\d*(?:[eE]-?\d+)?", m.group(2))]
    assert len(vals) == int(m.group(1)), (name, len(vals))
    return vals
ecc = table("ecc83Table")
dio = table("table_1n914")
q15 = lambda v: max(-32767, min(32767, int(round(v * 32767))))

FS, N = 44100, 1024
rnd = random.Random(7)
def env(i, t):           # an exponential fall, t seconds to -60 dB
    return math.exp(-6.9 * i / (FS * t))
def norm(x):
    m = max(abs(v) for v in x) or 1
    return [int(round(127 * v / m)) for v in x]
def hp(x, a=0.6):
    y, p, q = [], 0.0, 0.0
    for v in x:
        q = a * (q + v - p); p = v; y.append(q)
    return y
T = {}
# CLICK: a step, as a speaker's cone kicked: a few samples up, a fast fall (the LXR's "click" is such a pulse too)
T["CLICK"] = [(1.0 if i < 6 else 0.0) * 1 + (env(i, 0.004) * (-0.35) if i >= 6 else 0) for i in range(N)]
# TICK: high, short: a filtered noise burst
T["TICK"] = hp([rnd.uniform(-1, 1) * env(i, 0.006) for i in range(N)], 0.3)
# WOOD: a damped bar: two partials, 1.1 kHz and 2.9 kHz
T["WOOD"] = [env(i, 0.018) * (math.sin(2 * math.pi * 1100 * i / FS) + 0.5 * math.sin(2 * math.pi * 2920 * i / FS)) for i in range(N)]
# METAL: inharmonic, a struck plate's first partials
T["METAL"] = [env(i, 0.022) * sum(a * math.sin(2 * math.pi * f * i / FS + ph) for f, a, ph in
              ((1530, 1, 0), (2410, .8, 1), (3730, .6, 2), (5210, .5, .5), (7330, .35, 1.7))) for i in range(N)]
# NOISE: white, a short burst
T["NOISE"] = [rnd.uniform(-1, 1) * env(i, 0.012) for i in range(N)]
# ZAP: a sine falling 4 kHz -> 200 Hz in 15 ms
ph, T["ZAP"] = 0.0, []
for i in range(N):
    f = 200 + 3800 * math.exp(-i / (FS * 0.004)); ph += 2 * math.pi * f / FS; T["ZAP"].append(math.sin(ph) * env(i, 0.02))
# THUMP: a low half-sine body, 120 Hz
T["THUMP"] = [math.sin(math.pi * min(i / (FS / 240.0), 1.0)) * (1 if i < FS / 240 else env(i - FS / 240, 0.01)) * (1 if i < FS / 240 else math.cos(2 * math.pi * 120 * (i - FS / 240) / FS)) for i in range(N)]
# CRACK: a snapped stick: noise bursts 3 ms apart, band-passed
x = [0.0] * N
for b in (0, 130, 260):
    for i in range(b, min(N, b + 300)):
        x[i] += rnd.uniform(-1, 1) * env(i - b, 0.004) * (1 - b / 400)
T["CRACK"] = hp(x, 0.5)
NAMES = list(T)

print("/* SPDX-License-Identifier: GPL-3.0-only")
print(" * generated by tools/gen_xr_tables.py: do not edit */")
print("/* the TUBE (ECC83) and RAT (1N914) curves: from the LXR firmware (Copyright (C) 2012-2026 Erica Synths, GPL-3.0-only,")
print(" * Distortion.c), in Q15; index (x + 1) * 64 (TUBE, 129 points), (x + 1) * 128 (RAT, 257 points) */")
print("static const int16_t XR_TUBE[129] = {" + ", ".join(str(q15(v)) for v in ecc) + "};")
print("static const int16_t XR_DIODE[257] = {" + ", ".join(str(q15(v)) for v in dio) + "};")
print("/* the transients (cursed-os's own: tools/gen_xr_tables.py), 8 bits, 44.1 kHz, %d samples */" % N)
print("#define XR_TRN_N %d" % len(NAMES))
print("#define XR_TRN_LEN %du" % N)
print("static const int8_t XR_TRN[XR_TRN_N][XR_TRN_LEN] = {")
for k in NAMES:
    print("    {" + ", ".join(str(v) for v in norm(T[k])) + "},   /* %s */" % k)
print("};")
